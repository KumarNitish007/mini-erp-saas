using MiniErp.Application.Common;
using MiniErp.Application.Features.Invoices;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;

namespace MiniErp.Infrastructure.Pdf;

/// <summary>Renders a GST tax invoice (A4) with QuestPDF.</summary>
internal sealed class QuestPdfInvoiceGenerator : IInvoicePdfGenerator
{
    private const string Accent = "#1F3A93";
    private static string M(decimal v) => IndianNumberFormat.Money(v);

    public byte[] Generate(InvoiceDetailDto inv, InvoiceIssuer issuer) =>
        Document.Create(doc => doc.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(36);
            page.DefaultTextStyle(t => t.FontSize(9.5f).FontColor(Colors.Grey.Darken4));

            page.Header().Element(c => Header(c, inv, issuer));
            page.Content().PaddingVertical(14).Element(c => Body(c, inv));
            page.Footer().AlignCenter().Text(t =>
            {
                t.Span("Generated by MiniERP · Page ").FontSize(8).FontColor(Colors.Grey.Medium);
                t.CurrentPageNumber().FontSize(8).FontColor(Colors.Grey.Medium);
            });
        })).GeneratePdf();

    private static void Header(IContainer c, InvoiceDetailDto inv, InvoiceIssuer issuer) => c.Column(col =>
    {
        col.Item().Row(row =>
        {
            row.RelativeItem().Column(left =>
            {
                left.Item().Text(issuer.Name).FontSize(16).Bold().FontColor(Accent);
                if (issuer.Address is not null) left.Item().Text(issuer.Address);
                left.Item().Text($"State: {IndianStates.NameOf(issuer.StateCode)} ({issuer.StateCode})");
                if (issuer.Gstin is not null) left.Item().Text($"GSTIN: {issuer.Gstin}").SemiBold();
            });

            row.ConstantItem(190).AlignRight().Column(right =>
            {
                right.Item().AlignRight().Text(inv.Status == "Draft" ? "DRAFT INVOICE" : "TAX INVOICE").FontSize(15).Bold();
                right.Item().AlignRight().Text($"No: {inv.Number ?? "—"}").SemiBold();
                right.Item().AlignRight().Text($"Date: {inv.InvoiceDate:dd MMM yyyy}");
                right.Item().AlignRight().Text($"Due: {inv.DueDate:dd MMM yyyy}");
                if (inv.Status is "Paid" or "Cancelled")
                    right.Item().AlignRight().Text(inv.Status.ToUpperInvariant()).Bold()
                        .FontColor(inv.Status == "Paid" ? Colors.Green.Darken2 : Colors.Red.Darken2);
            });
        });
        col.Item().PaddingTop(10).LineHorizontal(1.5f).LineColor(Accent);
    });

    private static void Body(IContainer c, InvoiceDetailDto inv) => c.Column(col =>
    {
        col.Spacing(12);

        col.Item().Background(Colors.Grey.Lighten4).Padding(10).Column(b =>
        {
            b.Item().Text("BILL TO").FontSize(8).Bold().FontColor(Colors.Grey.Darken1);
            b.Item().Text(inv.Customer.Name).FontSize(11).SemiBold();
            if (inv.Customer.BillingAddress is not null) b.Item().Text(inv.Customer.BillingAddress);
            b.Item().Text($"Place of supply: {inv.Customer.StateName} ({inv.Customer.StateCode})");
            if (inv.Customer.Gstin is not null) b.Item().Text($"GSTIN: {inv.Customer.Gstin}");
        });

        col.Item().Table(table =>
        {
            table.ColumnsDefinition(cd =>
            {
                cd.ConstantColumn(24);
                cd.RelativeColumn(4);
                cd.RelativeColumn(1.2f);
                cd.RelativeColumn(1.5f);
                cd.RelativeColumn(1);
                cd.RelativeColumn(1.6f);
                cd.RelativeColumn(1.7f);
            });

            table.Header(h =>
            {
                foreach (var (text, right) in new[] { ("#", false), ("Item", false), ("Qty", true), ("Rate", true), ("GST %", true), ("Tax", true), ("Amount", true) })
                {
                    var cell = h.Cell().Background(Accent).PaddingVertical(5).PaddingHorizontal(4);
                    (right ? cell.AlignRight() : cell).Text(text).FontColor(Colors.White).SemiBold();
                }
            });

            var i = 1;
            foreach (var l in inv.Lines)
            {
                var bg = i % 2 == 0 ? Colors.Grey.Lighten5 : Colors.White;
                IContainer Cell() => table.Cell().Background(bg).BorderBottom(0.5f).BorderColor(Colors.Grey.Lighten2).PaddingVertical(4).PaddingHorizontal(4);

                Cell().Text(i++.ToString());
                Cell().Text(l.Description);
                Cell().AlignRight().Text(l.Quantity.ToString("0.###"));
                Cell().AlignRight().Text(M(l.UnitPrice));
                Cell().AlignRight().Text(l.GstRate.ToString("0.##"));
                Cell().AlignRight().Text(M(l.TaxAmount));
                Cell().AlignRight().Text(M(l.LineTotal));
            }
        });

        col.Item().Row(row =>
        {
            row.RelativeItem().PaddingRight(20).Column(left =>
            {
                left.Item().Text("Amount in words").FontSize(8).Bold().FontColor(Colors.Grey.Darken1);
                left.Item().Text(IndianNumberFormat.InWords(inv.GrandTotal)).Italic();
                if (inv.Notes is not null)
                {
                    left.Item().PaddingTop(8).Text("Notes").FontSize(8).Bold().FontColor(Colors.Grey.Darken1);
                    left.Item().Text(inv.Notes);
                }
            });

            row.ConstantItem(210).Column(t =>
            {
                void Line(string label, decimal value, bool strong = false)
                {
                    t.Item().PaddingVertical(2).Row(r =>
                    {
                        var l = r.RelativeItem().Text(label);
                        var v = r.ConstantItem(100).AlignRight().Text("INR " + M(value));
                        if (strong) { l.Bold(); v.Bold(); }
                    });
                }

                Line("Taxable value", inv.SubTotal);
                if (inv.IsInterState) Line("IGST", inv.IgstAmount);
                else
                {
                    Line("CGST", inv.CgstAmount);
                    Line("SGST", inv.SgstAmount);
                }
                t.Item().PaddingVertical(3).LineHorizontal(1).LineColor(Colors.Grey.Lighten1);
                Line("Grand total", inv.GrandTotal, strong: true);
            });
        });

        col.Item().PaddingTop(30).AlignRight().Text("Authorised signatory").FontColor(Colors.Grey.Darken1);
    });
}
